const clean = (s) => s.trim().replace(/\s+/g, ' ');

// Будує відповідність «категорія товару → розділ» з меню головної сторінки (cheerio).
export function buildGroupMap($) {
  const map = new Map(Object.entries(EXTRA));
  $('li.category-menu__item').each((_, li) => {
    const item = $(li);
    const top = clean(item.find('a.category-menu__link-wrap').first().text());
    if (!top) return;
    const group = RENAME[top] || top;
    map.set(top, group);
    item.find('.category-dropdown a').each((_, a) => {
      const name = clean($(a).text());
      if (name && !map.has(name)) map.set(name, group);
    });
  });
  return map;
}

export const groupOf = (category, map) => map.get(category) || 'Інше';
